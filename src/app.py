def explain_words(model, cleaned_text, n=8):
    """Show words with the strongest positive and negative contributions."""
    vectorizer = model.named_steps["tfidf"]
    classifier = model.named_steps["clf"]

    feature_names = vectorizer.get_feature_names_out()
    article_vector = vectorizer.transform([cleaned_text])

    contributions = article_vector.multiply(
        classifier.coef_[0]
    ).toarray()[0]

    present_indices = np.flatnonzero(
        article_vector.toarray()[0]
    )

    fake_indices = sorted(
        present_indices,
        key=lambda i: contributions[i],
    )[:n]

    real_indices = sorted(
        present_indices,
        key=lambda i: contributions[i],
        reverse=True,
    )[:n]

    fake_words = [
        (feature_names[i], float(contributions[i]))
        for i in fake_indices
        if contributions[i] < 0
    ]

    real_words = [
        (feature_names[i], float(contributions[i]))
        for i in real_indices
        if contributions[i] > 0
    ]

    return fake_words, real_words


def show_confusion_matrix(matrix):
    """Display a confusion matrix with actual and predicted labels."""
    labels = ["Fake", "Real"]

    frame = pd.DataFrame(
        matrix,
        index=[f"Actual {label}" for label in labels],
        columns=[f"Predicted {label}" for label in labels],
    )

    st.dataframe(frame, use_container_width=True)


